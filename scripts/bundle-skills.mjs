import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = join(root, "docs", "skills", "browser-execute");
const target = join(root, "packages", "core", "src", "skills.generated.ts");

const work = mkdtempSync(join(tmpdir(), "openbot-skills-"));
try {
  const archive = join(work, "browser-execute.tar.gz");
  execFileSync("tar", ["-czf", archive, "-C", dirname(source), "browser-execute"], {
    stdio: "inherit",
  });
  const base64 = readFileSync(archive).toString("base64");
  const banner =
    "// AUTO-GENERATED by scripts/bundle-skills.mjs. Do not edit by hand.\n" +
    "// Source: docs/skills/browser-execute (vendored from browser-use/browsercode\n" +
    "// and browser-use/browser-harness-js, MIT). Regenerate with `pnpm skills:bundle`.\n";
  writeFileSync(
    target,
    `${banner}export const BROWSER_SKILLS_B64 =\n  "${base64}";\n`,
  );
  console.log(
    `wrote ${target} (${(base64.length / 1024).toFixed(1)} KiB base64, ${(readFileSync(archive).length / 1024).toFixed(1)} KiB tar.gz)`,
  );
} finally {
  rmSync(work, { recursive: true, force: true });
}
